export function getProfile(id: string): CameraProfile {
  return PROFILES.find((p) => p.id === id) ?? PROFILES[0];
}

export function megapixels(p: CameraProfile): string {
  const mp = (p.output.width * p.output.height) / 1e6;
  return mp < 1 ? `${(mp).toFixed(1)} MP` : `${Number(mp.toFixed(1))} MP`;
}
